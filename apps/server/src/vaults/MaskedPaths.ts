/**
 * Spec 5 ticket 05: every door of the Hub (WS methods, HTTP endpoints, raw routes, MCP tools, the
 * executor wire), each by name: how a Thread's process output or a checkout's text reaches it
 * masked, or why it carries none. A new door has no rule and fails `MaskedPaths.test.ts`; a door
 * marked masked is called with a secret by `MaskedDoors.test.ts`.
 */
