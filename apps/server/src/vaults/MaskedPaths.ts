/**
 * `masked`: by the named code; `history`: from the store EventSink masks; `noProcessText`: ids,
 * names, status or what Users typed; `unmasked`: accepted (docs/internals/secrets.md).
 */
export type DoorRule =
  | { readonly masked: string }
  | { readonly history: string }
  | { readonly noProcessText: string }
  | { readonly unmasked: string };

const HISTORY: DoorRule = { history: "a Thread's history, from the masked store" };
const masked = (by: string): DoorRule => ({ masked: by });
const none = (what: string): DoorRule => ({ noProcessText: what });

